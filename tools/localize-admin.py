def add_keys(path, keys):
    with io.open(path, encoding='utf-8') as f:
        s = f.read()
    assert s.rstrip().endswith('};'), path
    lines = ["  '%s': %s," % (k, repr(v)) for k, v in keys.items()]
    s = s.rstrip()[: -len('};')].rstrip() + '\n' + '\n'.join(lines) + '\n};\n'
    with io.open(path, 'w', encoding='utf-8') as f:
        f.write(s)
    print('keys added to', path)


